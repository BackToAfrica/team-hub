create table if not exists public.vod_analysis_jobs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  team_id bigint not null default public.my_team(),
  review_id bigint not null references public.reviews(id) on delete cascade,
  source text not null default 'youtube' check (source in ('youtube')),
  source_url text not null,
  youtube_video_id text not null,
  video_title text,
  channel_title text,
  thumbnail_url text,
  duration_seconds integer,
  status text not null default 'awaiting_media' check (status in ('imported','awaiting_media','queued','processing','needs_review','completed','failed')),
  stage text not null default 'metadata_import',
  progress integer not null default 0 check (progress between 0 and 100),
  provider text,
  provider_asset_id text,
  provider_task_id text,
  error_message text,
  metadata jsonb not null default '{}'::jsonb,
  result jsonb not null default '{}'::jsonb
);
create index if not exists vod_analysis_jobs_team_created_idx on public.vod_analysis_jobs(team_id, created_at desc);
create index if not exists vod_analysis_jobs_review_idx on public.vod_analysis_jobs(review_id);
create unique index if not exists vod_analysis_jobs_review_unique_idx on public.vod_analysis_jobs(review_id);
alter table public.vod_analysis_jobs enable row level security;
revoke all on public.vod_analysis_jobs from anon;
revoke all on public.vod_analysis_jobs from authenticated;
grant select, insert, update on public.vod_analysis_jobs to authenticated;
create policy vod_jobs_staff_select on public.vod_analysis_jobs for select to authenticated using (team_id = public.my_team() and public.is_staff());
create policy vod_jobs_staff_insert on public.vod_analysis_jobs for insert to authenticated with check (team_id = public.my_team() and public.is_staff());
create policy vod_jobs_staff_update on public.vod_analysis_jobs for update to authenticated using (team_id = public.my_team() and public.is_staff()) with check (team_id = public.my_team() and public.is_staff());
