-- Tryouts pipeline, season goals, calendar feed, error log and a health check for the owner.

-- ---------------------------------------------------------------- tryouts (staff only)
create table if not exists public.tryouts (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  team_id bigint not null default public.my_team() references public.teams(id) on delete cascade,
  name text not null,
  riot_id text,
  discord text,
  role text,
  rank text,
  status text not null default 'Applied',
  trial_start date,
  trial_end date,
  scores jsonb not null default '{}'::jsonb,
  notes text,
  source text
);
create index if not exists tryouts_team_idx on public.tryouts(team_id);
alter table public.tryouts enable row level security;
drop policy if exists tryouts_staff on public.tryouts;
create policy tryouts_staff on public.tryouts for all
  using (team_id = (select public.my_team()) and (select public.is_staff()))
  with check (team_id = (select public.my_team()) and (select public.is_staff()));
grant select, insert, update, delete on public.tryouts to authenticated;

-- ---------------------------------------------------------------- season goals (everyone reads, staff writes)
create table if not exists public.team_goals (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  team_id bigint not null default public.my_team() references public.teams(id) on delete cascade,
  title text not null,
  metric text,
  target numeric,
  since date,
  deadline date,
  notes text,
  done boolean not null default false,
  sort int
);
create index if not exists team_goals_team_idx on public.team_goals(team_id);
alter table public.team_goals enable row level security;
drop policy if exists team_goals_read on public.team_goals;
create policy team_goals_read on public.team_goals for select using (team_id = (select public.my_team()) and (select public.is_member()));
drop policy if exists team_goals_staff on public.team_goals;
create policy team_goals_staff on public.team_goals for all
  using (team_id = (select public.my_team()) and (select public.is_staff()))
  with check (team_id = (select public.my_team()) and (select public.is_staff()));
grant select, insert, update, delete on public.team_goals to authenticated;

-- ---------------------------------------------------------------- calendar feed
-- Each team gets a secret feed address (kept in the private schema, not readable through the API).
create schema if not exists private;
create table if not exists private.team_calendar (
  team_id bigint primary key references public.teams(id) on delete cascade,
  token text not null default (replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', ''))
);
alter table private.team_calendar enable row level security;
create or replace function public.my_calendar_token() returns text
  language plpgsql security definer set search_path = '' as $$
declare t bigint := public.my_team(); tok text;
begin
  if t is null or not public.is_member() then return null; end if;
  insert into private.team_calendar (team_id) values (t) on conflict (team_id) do nothing;
  select token into tok from private.team_calendar where team_id = t;
  return tok;
end $$;
create or replace function public.rotate_calendar_token() returns text
  language plpgsql security definer set search_path = '' as $$
declare t bigint := public.my_team(); tok text;
begin
  if t is null or not public.is_coach() then raise exception 'Only the coach can reset the calendar link.'; end if;
  insert into private.team_calendar (team_id) values (t)
    on conflict (team_id) do update set token = replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', '')
    returning token into tok;
  return tok;
end $$;
create or replace function public.calendar_team(t text) returns bigint
  language sql stable security definer set search_path = '' as $$ select team_id from private.team_calendar where token = t $$;
revoke execute on function public.calendar_team(text) from public, anon, authenticated;
grant execute on function public.calendar_team(text) to service_role;
grant execute on function public.my_calendar_token() to authenticated;
grant execute on function public.rotate_calendar_token() to authenticated;

-- ---------------------------------------------------------------- error log
create table if not exists public.app_errors (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid default auth.uid(),
  team_id bigint default public.my_team(),
  message text,
  stack text,
  url text,
  ua text
);
create index if not exists app_errors_created_idx on public.app_errors(created_at desc);
alter table public.app_errors enable row level security;
drop policy if exists app_errors_insert on public.app_errors;
create policy app_errors_insert on public.app_errors for insert to authenticated with check (user_id = (select auth.uid()));
drop policy if exists app_errors_admin on public.app_errors;
create policy app_errors_admin on public.app_errors for select using ((select public.is_admin()));
drop policy if exists app_errors_admin_del on public.app_errors;
create policy app_errors_admin_del on public.app_errors for delete using ((select public.is_admin()));
grant select, insert, delete on public.app_errors to authenticated;

-- ---------------------------------------------------------------- health check (owner only)
create or replace function public.admin_health() returns jsonb
  language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.is_admin() then return null; end if;
  return jsonb_build_object(
    'cron', (select coalesce(jsonb_agg(jsonb_build_object('start', d.start_time, 'status', d.status, 'msg', left(d.return_message, 200)) order by d.start_time desc), '[]'::jsonb)
             from (select * from cron.job_run_details where jobid in (select jobid from cron.job where jobname = 'riot-auto-sync') order by start_time desc limit 8) d),
    'http', (select coalesce(jsonb_agg(jsonb_build_object('status', h.status_code, 'body', left(h.content::text, 160), 'err', h.error_msg, 'at', h.created) order by h.id desc), '[]'::jsonb)
             from (select * from net._http_response order by id desc limit 8) h),
    'links', (select count(*) from public.riot_links),
    'stale_links', (select count(*) from public.riot_links where synced_at is null or synced_at < now() - interval '3 hours'),
    'errors_24h', (select count(*) from public.app_errors where created_at > now() - interval '24 hours'),
    'teams', (select count(*) from public.teams),
    'members', (select count(*) from public.profiles where team_id is not null)
  );
end $$;
grant execute on function public.admin_health() to authenticated;
