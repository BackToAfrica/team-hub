-- ---------------------------------------------------------------- faster row-level security
-- Wrap the team / role checks in a sub-select so Postgres runs them once per query instead of once per row.
do $$
declare p record; q text; c text; stmt text;
  fn_re constant text := '(?<!SELECT )(?<![.\w])(my_team|is_staff|is_coach|is_member|is_admin|my_ign)\(\)';
  cs_re constant text := '(?<!SELECT )(?<![.\w])can_see\(([^()]*)\)';
begin
  for p in select * from pg_policies where schemaname = 'public' loop
    q := regexp_replace(regexp_replace(p.qual, fn_re, '(SELECT \1())', 'g'), cs_re, '(SELECT can_see(\1))', 'g');
    c := regexp_replace(regexp_replace(p.with_check, fn_re, '(SELECT \1())', 'g'), cs_re, '(SELECT can_see(\1))', 'g');
    if q is distinct from p.qual or c is distinct from p.with_check then
      stmt := format('alter policy %I on public.%I', p.policyname, p.tablename);
      if q is not null then stmt := stmt || ' using (' || q || ')'; end if;
      if c is not null then stmt := stmt || ' with check (' || c || ')'; end if;
      execute stmt;
    end if;
  end loop;
end $$;

-- "<table>_coach" policies that are exact copies of "<table>_staff" with is_coach() instead of is_staff()
-- are redundant (every coach is staff). Dropping them removes duplicate checks on every query.
do $$
declare p record;
begin
  for p in
    select a.tablename, a.policyname from pg_policies a join pg_policies b
      on a.schemaname = b.schemaname and a.tablename = b.tablename and a.cmd = b.cmd
    where a.schemaname = 'public' and a.policyname = a.tablename || '_coach' and b.policyname = b.tablename || '_staff'
      and replace(replace(a.qual, 'is_coach() AS is_coach', 'is_staff() AS is_staff'), 'is_coach()', 'is_staff()') = b.qual
      and coalesce(replace(replace(a.with_check, 'is_coach() AS is_coach', 'is_staff() AS is_staff'), 'is_coach()', 'is_staff()'), '') = coalesce(b.with_check, '')
  loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end $$;

-- ---------------------------------------------------------------- scheduled Riot sync
-- Every 20 minutes the database asks riot-sync to refresh the players who haven't synced in the last hour,
-- so scrims and stats arrive without anyone pressing sync. The token lives in a private schema that the
-- API can't read; riot-sync checks it with cron_token_ok(), which only the service role can call.
create extension if not exists pg_net with schema extensions;
create extension if not exists pg_cron;
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
create table if not exists private.cron_token (
  id int primary key default 1 check (id = 1),
  token text not null default (replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', ''))
);
insert into private.cron_token (id) values (1) on conflict (id) do nothing;
create or replace function public.cron_token_ok(t text) returns boolean
  language sql stable security definer set search_path = ''
  as $$ select exists (select 1 from private.cron_token where token = t) $$;
revoke execute on function public.cron_token_ok(text) from public, anon, authenticated;
grant execute on function public.cron_token_ok(text) to service_role;

