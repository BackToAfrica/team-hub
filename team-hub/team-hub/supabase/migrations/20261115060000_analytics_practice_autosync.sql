-- ---------------------------------------------------------------- practice plans
create table if not exists public.practice_plans (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  team_id bigint not null default public.my_team() references public.teams(id) on delete cascade,
  week_start date not null,
  title text,
  items jsonb not null default '[]'::jsonb,
  notes text,
  published boolean not null default false
);
create index if not exists practice_plans_team_week_idx on public.practice_plans(team_id, week_start desc);
alter table public.practice_plans enable row level security;
drop policy if exists practice_plans_read on public.practice_plans;
create policy practice_plans_read on public.practice_plans for select
  using (team_id = (select public.my_team()) and (select public.is_member()) and (published or (select public.is_staff())));
drop policy if exists practice_plans_staff on public.practice_plans;
create policy practice_plans_staff on public.practice_plans for all
  using (team_id = (select public.my_team()) and (select public.is_staff()))
  with check (team_id = (select public.my_team()) and (select public.is_staff()));
grant select, insert, update, delete on public.practice_plans to authenticated;

