-- Riot account link + match stats pulled from the HenrikDev API by the riot-sync Edge Function.
-- Privacy: a player's Riot ID and full match history are visible ONLY to that player.
-- The team (coaches included) sees only riot_summary: games, K/D, HS% and a few averages.

-- 1) The link itself. Only the player can read it; only the Edge Function (service role) writes it.
create table if not exists public.riot_links (
  user_id    uuid primary key references public.profiles(id) on delete cascade,
  riot_name  text not null,
  riot_tag   text not null,
  region     text not null,          -- HenrikDev affinity: na / eu / ap / kr / latam / br
  puuid      text not null,
  linked_at  timestamptz not null default now(),
  synced_at  timestamptz
);
alter table public.riot_links enable row level security;
revoke all on public.riot_links from anon, authenticated;
grant select, delete on public.riot_links to authenticated;
drop policy if exists riot_links_own_read on public.riot_links;
create policy riot_links_own_read on public.riot_links for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists riot_links_own_delete on public.riot_links;
create policy riot_links_own_delete on public.riot_links for delete to authenticated using (user_id = (select auth.uid()));

-- 2) One row per player per match. Owner-only.
create table if not exists public.riot_matches (
  id             bigint generated by default as identity primary key,
  user_id        uuid not null references public.profiles(id) on delete cascade,
  team_id        bigint references public.teams(id) on delete set null,
  match_id       text not null,
  started_at     timestamptz,
  map            text,
  queue          text,                 -- competitive / unrated / custom / premier / swiftplay ...
  agent          text,
  won            boolean,
  rounds_won     integer,
  rounds_lost    integer,
  rounds         integer,
  score          integer,              -- combat score (ACS = score / rounds)
  kills          integer,
  deaths         integer,
  assists        integer,
  headshots      integer,
  bodyshots      integer,
  legshots       integer,
  damage         integer,
  first_kills    integer,
  first_deaths   integer,
  trades         integer,              -- kills that avenged a teammate within 3 s
  traded_deaths  integer,              -- own deaths a teammate avenged within 3 s
  detail         jsonb not null default '{}'::jsonb,  -- scoreboard of the match (public game data)
  created_at     timestamptz not null default now(),
  unique (user_id, match_id)
);
create index if not exists riot_matches_user_idx on public.riot_matches(user_id, started_at desc);
create index if not exists riot_matches_team_idx on public.riot_matches(team_id);
alter table public.riot_matches enable row level security;
revoke all on public.riot_matches from anon, authenticated;
grant select on public.riot_matches to authenticated;
drop policy if exists riot_matches_own_read on public.riot_matches;
create policy riot_matches_own_read on public.riot_matches for select to authenticated using (user_id = (select auth.uid()));

-- 3) The team-visible summary shown under each player's name.
create table if not exists public.riot_summary (
  user_id      uuid primary key references public.profiles(id) on delete cascade,
  team_id      bigint references public.teams(id) on delete cascade,
  games        integer not null default 0,
  wins         integer not null default 0,
  kills        integer not null default 0,
  deaths       integer not null default 0,
  assists      integer not null default 0,
  kd           numeric,
  hs_pct       numeric,                 -- headshots / all hits
  acs          numeric,
  adr          numeric,
  first_kills  integer not null default 0,
  first_deaths integer not null default 0,
  trades       integer not null default 0,
  last_game_at timestamptz,
  updated_at   timestamptz not null default now()
);
alter table public.riot_summary enable row level security;
revoke all on public.riot_summary from anon, authenticated;
grant select on public.riot_summary to authenticated;
drop policy if exists riot_summary_team_read on public.riot_summary;
create policy riot_summary_team_read on public.riot_summary for select to authenticated
  using (user_id = (select auth.uid()) or (team_id = public.my_team() and public.is_member()));

-- Unlinking also removes the player's pulled games and summary.
create or replace function public.riot_unlink_cleanup() returns trigger
language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
begin
  delete from public.riot_matches where user_id = old.user_id;
  delete from public.riot_summary where user_id = old.user_id;
  return old;
end $$;
revoke execute on function public.riot_unlink_cleanup() from public, anon, authenticated;
drop trigger if exists riot_unlink_cleanup on public.riot_links;
create trigger riot_unlink_cleanup after delete on public.riot_links for each row execute function public.riot_unlink_cleanup();
